macro_rules! words {
    ($($(#[$doc:meta])* $name:ident: $ja:expr, $en:expr;)*) => {
        #[derive(Debug, PartialEq, Eq)]
        pub struct Words {
            $($(#[$doc])* pub $name: &'static str,)*
        }
        pub const JA: Words = Words { $($name: $ja,)* };
        pub const EN: Words = Words { $($name: $en,)* };

        #[cfg(test)]
        impl Words {
            fn all(&self) -> Vec<&'static str> {
                vec![$(self.$name,)*]
            }
        }
    };
}

